/*

- 2FN(Segunda Forma Normal) .-
  -Este EN 1FN
  -Cada Registro Sea Unico.
  -Clave principal de una solo columna que no dependa funcionalmente de ningun subconjunto de relacion de la 
   clave candidata
*/

CREATE TABLE MIEMBROS_2FN(
    IDMIEMBRO INT IDENTITY(1,1) PRIMARY KEY,
	NOMBRECOMPLETO VARCHAR(200),
	DIRECCION VARCHAR(150),
	SALUDO VARCHAR(4))

