/*
Tipos de Formas Normales en DBMS
- 1FN(Primera Forma Normal) .-
  -Garantiza que la tabla de la BD este organizada de manera que 
  cada columna contenga valores atomicos(Divisible)
  -Cada Registro Sea Unico.
  -Eliminar grupos repetidos.
*/

CREATE TABLE INFORMACION_1FN(
	ID INT IDENTITY(1,1) PRIMARY KEY,
	NOMBRECOMPLETO VARCHAR(200),
	DIRECCION VARCHAR(150),
	PELICULASRENTADAS VARCHAR(MAX),
	SALUDO VARCHAR(4))

